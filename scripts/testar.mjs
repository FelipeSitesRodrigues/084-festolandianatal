/**
 * Teste de funcionamento no Chrome da máquina: menu do celular, âncoras, acordeão das
 * dúvidas e o formulário (erro com campo vazio, máscara e a mensagem montada pro WhatsApp).
 * Uso: node scripts/testar.mjs   (com o servidor no ar, npm run serve)
 */
import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new' })
const pg = await b.newPage()
const erros = []
pg.on('pageerror', (e) => erros.push(e.message))
pg.on('console', (m) => m.type() === 'error' && erros.push(m.text()))
let aberto = null
b.on('targetcreated', async (t) => { if (t.url().includes('wa.me')) aberto = t.url() })
// celular: menu
await pg.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
await pg.goto('http://localhost:3084/', { waitUntil: 'networkidle0' })
await pg.click('.topo__menu')
await new Promise((r) => setTimeout(r, 500))
const menu = await pg.evaluate(() => ({ visivel: !document.getElementById('menu-cel').hidden, exp: document.querySelector('.topo__menu').getAttribute('aria-expanded'), inerte: document.getElementById('conteudo').inert }))
await pg.click('.menu-cel__links a[href="#elenco"]')
await new Promise((r) => setTimeout(r, 1800))
const ancora = await pg.evaluate(() => ({ menuFechou: document.getElementById('menu-cel').hidden, topoElenco: Math.round(document.getElementById('elenco').getBoundingClientRect().top), alturaTopo: document.getElementById('topo').getBoundingClientRect().height }))
console.log('menu:', JSON.stringify(menu), 'âncora:', JSON.stringify(ancora))
// computador: FAQ, âncora do orçamento e formulário
await pg.setViewport({ width: 1440, height: 900 })
await pg.goto('http://localhost:3084/', { waitUntil: 'networkidle0' })
await pg.click('.topo__links a[href="#duvidas"]')
await new Promise((r) => setTimeout(r, 1800))
const faqTopo = await pg.evaluate(() => Math.round(document.getElementById('duvidas').getBoundingClientRect().top))
await pg.click('#faq-b2')
await new Promise((r) => setTimeout(r, 600))
const faq = await pg.evaluate(() => ({ b2: document.getElementById('faq-b2').getAttribute('aria-expanded'), alturaR2: Math.round(document.getElementById('faq-r2').getBoundingClientRect().height), b1: document.getElementById('faq-b1').getAttribute('aria-expanded') }))
console.log('faq topo:', faqTopo, 'acordeão:', JSON.stringify(faq))
await pg.evaluate(() => document.getElementById('orcamento').scrollIntoView())
await new Promise((r) => setTimeout(r, 800))
await pg.click('.form__enviar')
await new Promise((r) => setTimeout(r, 300))
const errosForm = await pg.evaluate(() => [...document.querySelectorAll('.campo__erro')].map((e) => e.textContent).filter(Boolean))
console.log('envio vazio, erros:', errosForm.join(' | '), '· foco em', await pg.evaluate(() => document.activeElement.name))
await pg.type('#f-nome', 'Mariana Teste')
await pg.type('#f-whatsapp', '11987654321')
await pg.select('#f-tipo', 'Noite de Natal em casa')
await pg.evaluate(() => { const d = document.getElementById('f-data'); d.value = '2026-12-24'; d.dispatchEvent(new Event('input', { bubbles: true })) })
await pg.evaluate(() => { const d = document.getElementById('f-horario'); d.value = '20:30' })
await pg.type('#f-criancas', '6')
await pg.click('.chip input[value="Mamãe Noel"]')
await pg.click('.aceite input')
await pg.click('.form__enviar')
await new Promise((r) => setTimeout(r, 1200))
const sucesso = await pg.evaluate(() => !document.querySelector('.form__sucesso').hidden)
const link = await pg.evaluate(() => document.querySelector('.form__link').href)
console.log('sucesso visível:', sucesso, '· máscara:', await pg.$eval('#f-whatsapp', (e) => e.value))
console.log('mensagem:\n' + decodeURIComponent(link.split('text=')[1]))
console.log('aba aberta:', aberto ? 'sim' : 'não', '· erros de JS:', erros.length ? erros.join(' | ') : 'nenhum')
await b.close()
